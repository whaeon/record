#!/bin/sh
set -eu

ROOT="$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)"
SNAPSHOT="${1:-$ROOT/backups/data.db.20261116}"
DSN="${DATABASE_URL:-postgres://record:record@127.0.0.1:5432/record?sslmode=disable}"
SCHEMA="$ROOT/internal/db/schema.sql"

if [ ! -f "$SNAPSHOT" ]; then
	echo "sqlite snapshot not found: $SNAPSHOT" >&2
	exit 1
fi

psql "$DSN" -v ON_ERROR_STOP=1 -f "$SCHEMA"
psql "$DSN" -v ON_ERROR_STOP=1 <<'SQL'
ALTER TABLE strategies ALTER COLUMN id SET GENERATED BY DEFAULT;
ALTER TABLE strategy_revisions ALTER COLUMN id SET GENERATED BY DEFAULT;
ALTER TABLE strategy_metrics ALTER COLUMN id SET GENERATED BY DEFAULT;
ALTER TABLE review_notes ALTER COLUMN id SET GENERATED BY DEFAULT;
SQL

LOAD_FILE="$(mktemp)"
trap 'rm -f "$LOAD_FILE"' EXIT

cat > "$LOAD_FILE" <<EOF
LOAD DATABASE
     FROM sqlite://$SNAPSHOT
     INTO $DSN

 WITH data only, truncate, disable triggers, reset sequences;
EOF

pgloader "$LOAD_FILE"

psql "$DSN" -v ON_ERROR_STOP=1 <<'SQL'
DROP TABLE IF EXISTS sqlite_sequence;
DROP TABLE IF EXISTS sqlite_stat1;
ALTER TABLE strategies ALTER COLUMN id SET GENERATED ALWAYS;
ALTER TABLE strategy_revisions ALTER COLUMN id SET GENERATED ALWAYS;
ALTER TABLE strategy_metrics ALTER COLUMN id SET GENERATED ALWAYS;
ALTER TABLE review_notes ALTER COLUMN id SET GENERATED ALWAYS;
SELECT setval(pg_get_serial_sequence('strategies', 'id'), COALESCE((SELECT MAX(id) FROM strategies), 1), true);
SELECT setval(pg_get_serial_sequence('strategy_revisions', 'id'), COALESCE((SELECT MAX(id) FROM strategy_revisions), 1), true);
SELECT setval(pg_get_serial_sequence('strategy_metrics', 'id'), COALESCE((SELECT MAX(id) FROM strategy_metrics), 1), true);
SELECT setval(pg_get_serial_sequence('review_notes', 'id'), COALESCE((SELECT MAX(id) FROM review_notes), 1), true);
SQL
